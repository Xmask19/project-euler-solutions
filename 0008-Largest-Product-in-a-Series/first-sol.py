def largest_prod_str(n: int, string: str) -> int:
    string = str(string)
    largest = 0
    for i in range(len(string) - n + 1):
        substring = string[i: i + n]
        prod = 1
        for digit in substring:
            prod *= int(digit)
        if prod > largest:
            largest = prod
    return largest


